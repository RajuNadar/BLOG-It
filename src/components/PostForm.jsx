import { useCallback, useDebugValue, useEffect } from "react"
import { useForm } from "react-hook-form"
import { Button, Input, Select, RTE } from "./index"
import { Link, useNavigate } from "react-router-dom"
import { useSelector } from "react-redux"
import uploadServices from "../services/upload"
import blogServices from "../services/blog"

export default function PostForm({ post }) {

    const { register, handleSubmit, watch, getValues, setValue, control } = useForm({
        defaultValues: {
            title: post?.title || "",
            slug: post?.slug || "",
            content: post?.content || "",
            status: post?.status || "active"
        }
    })
    const navigate = useNavigate()
    const userData = useSelector((state) => state.auth.userData)
    console.log("userr datta", userData);

    const submit = async (data) => {
        if (post) {
            const file = data.image[0] && data.image
                ? await uploadServices.uploadFile(data.image[0])
                : null
            if (file && post.featuredImage) {
                uploadServices.deleteFile(post.featuredImage)
            }
            const dbPost = await blogServices.updatePost(post.$id, {
                ...data,
                featuredImage: file ? file.$id : post.featuredImage,
            })
            console.log("dbPost", dbPost);
            if (dbPost) {
                navigate(`/post/${dbPost.$id}`)
            }
        } else {
            const file = data.image && data.image[0]
                ? await uploadServices.uploadFile(data.image[0])
                : null

            const dbPost = await blogServices.createPost({
                ...data,
                featuredImage: file ? file.$id : null,
                userId: userData.$id
            })

            if (dbPost) {
                navigate(`/post/${dbPost.$id}`)
            }
        }
    }

    const slugTransform = useCallback((value) => {
        if (value && typeof value === 'string') {
            return value
                .trim()
                .toLowerCase()
                .replace(/\s/g, '-')
        } else {
            return ''
        }
    }, [])

    useEffect(() => {
        const subscription = watch((value, { name }) => {
            if (name === "title") {
                setValue(
                    "slug",
                    slugTransform(value.title))
            }
        })
        return () => {
            subscription.unsubscribe()
        }
    }, [watch, slugTransform, setValue,])

    return (
        <form className="border-2 max-w-7xl mx-auto h-full border-base-border bg-base-surface p-5 my-5 rounded-2xl " onSubmit={handleSubmit(submit)}>
            <h2 className="text-center text-lg font-bold underline mb-3">{post ? 'Your Editing a Post' : 'Create a New Post'}</h2>
            <div className="w-full h-full flex flex-wrap">
                <div className="w-2/3 min-h-full px-2 space-y-6">
                    <Input
                        label="Your Post Title"
                        placeholder="Enter Title"
                        className="border-2 text-primary-text  border-base-border p-2 rounded-xl bg-base-main    "
                        {...register("title", {
                            required: true
                        })}
                    />
                    <Input
                        label="Your Post Slug"
                        placeholder="Your slug will be auto generated by your post title you can also change it"
                        className="border-2 text-primary-text border-base-border p-2 rounded-xl bg-base-main"
                        {...register("slug", {
                            required: true
                        })}
                        onInput={(e) => {
                            setValue("slug", slugTransform(e.currentTarget.value), {
                                shouldValidate: true
                            })
                        }}
                    />

                    <RTE
                        label="Post Content"
                        name="content"
                        control={control}
                        defaultValue={getValues("content")}
                    />
                </div>
                <div className="w-1/3 px-2">
                    
                    <div>
                        <Input
                            label="Featured Image"
                            placeholder="Enter image"
                            type="file"
                            className="border-2 text-primary-text border-base-border p-2 rounded-xl bg-base-main"
                            accept="image/png, image/jpg, image/jpeg, image/gif"
                            {...register("image", { required: false })}
                        />
                        <p className="text-sm">{post?.featuredImage ? '*Update or change your current post image (optional).' : '*you can also add a image to your post (optional)'}</p>
                        {post?.featuredImage && (
                            <div className="w-full h-100 mt-4">
                                <img
                                    src={uploadServices.getFilePreview(post.featuredImage)}
                                    alt={post?.title}
                                    className="rounded-lg w-full max-h-full object-fit"
                                />
                            </div>
                        )}
                    </div>

                    <Select
                        options={["Active", "Inactive"]}
                        label="Status :"
                        className="mb-3 text-md font-light cursor-pointer"
                        {...register("status", { required: true })}
                    />
                    <Button
                        type="submit">
                        {post ? "Update" : "Add Post"}
                    </Button>
                    <Link
                        to={"/all-posts"}
                        className={`ml-3 bg-accent text-base-main px-4 py-2 rounded-lg hover:bg-accent-hover transition-all font-semibold ${post ? 'bg-red-500 hover:bg-red-400' : ''}`}>{post ? 'Discard Changes' : 'Go Back'}
                    </Link>

                </div>
            </div>
        </form>
    )
}
